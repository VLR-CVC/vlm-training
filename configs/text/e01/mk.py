"""Generate the T04/EXP-009 run configs: python configs/text/e01/mk.py NAME KIND STEPS WARMUP SAVE [key=value ...]
KIND = engram | lora<rank>; extra key=value pairs patch [training]/[data] lines (e.g. lr_lora=3e-4)."""
import re, sys
from pathlib import Path
here = Path(__file__).parent
name, kind, steps, warm, save, *kv = sys.argv[1:]
t = (here / "engram-pilot.toml").read_text().split("\n", 1)[1]
t = t.replace('run_name = "e01-engram-pilot"', f'run_name = "e01-{name}"')
t = t.replace("checkpoints/e01/engram-pilot", f"checkpoints/e01/{name}")
t = re.sub(r"total_steps = \d+", f"total_steps = {steps}", t)
t = re.sub(r"warmup_steps = \d+", f"warmup_steps = {warm}", t)
t = re.sub(r"save_steps = \d+", f"save_steps = {save}", t)
if kind.startswith("lora"):
    r = int(kind[4:])
    t = t.replace('model_name = "Qwen/Qwen3.5-0.8B+engram"', 'model_name = "Qwen/Qwen3.5-0.8B+lora"')
    t = t.replace("engram = true\ntrain_engram = true", f"engram = false\nlora_rank = {r}\nlora_alpha = {2 * r}")
    t = t.replace("lr_engram = 1e-3", "lr_lora = 2e-4")
for item in kv:
    k, v = item.split("=", 1)
    t, n = re.subn(rf"^{k} = .*$", f"{k} = {v}", t, flags=re.M)
    if not n:
        t = t.replace("[data]\n", f"[data]\n{k} = {v}\n") if k in ("tokens_per_microbatch",) else t.replace("max_grad_norm", f"{k} = {v}\nmax_grad_norm")
(here / f"{name}.toml").write_text(f"# T04/EXP-009 {name} ({kind}), generated by mk.py {' '.join(sys.argv[1:])}\n" + t)
print(here / f"{name}.toml")
