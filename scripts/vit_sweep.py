"""Does dropping the vision encoder buy MFU, and does that depend on image density?

    python scripts/vit_sweep.py                    # run every cell, then report
    python scripts/vit_sweep.py --report-only      # re-read logs already on disk
    python scripts/vit_sweep.py --gpus 4           # everything on one card

The claim under test: the ViT is an MFU tax that grows with the number of images
in a batch -- VLM training lands near 25% MFU where text-only passes 35%. So the
axis that matters is IMAGE DENSITY, not sequence length:

  plotqa_cot    CoT answers, long text per image. 1-4 samples fill a 4096 row, so
                very few images per sequence. The LOW-density end.
  llava_recap   captions, short text per image. Many more images per row for the
                same token budget. The HIGH-density end.

Three arms per (size, data) cell:

  vlm            the real model, native ViT.
  novit          vision_config.depth = 0, decoder UNTOUCHED. The tower collapses to
                 patch_embed -> pos_embed -> merger, which is exactly a decoder-only
                 model handed patch embeddings. SMALLER than vlm -- this isolates the
                 ViT's own cost.
  novit_matched  depth 0 plus enough decoder layers to recover the parameter count
                 (0.8B 24->28, -0.24%; 2B 24->29, -0.66%). The same-size comparison.
                 Its gap to `novit` is the cost of spending those parameters on
                 decoder layers rather than on a tower.

`novit` also gives the ViT's share of modeled FLOPs for free, without instrumenting
the trainer: 1 - (novit TFLOP/step) / (vlm TFLOP/step). That is the quantitative
statement of "how image-dense is this data".

MFU here is computed against --peak-tflops, NOT against the trainer's own figure:
train_qwen.py:313 hardcodes peak_tflops_per_gpu = 989.4 (H100 bf16), so every `mfu`
in these logs reads ~5x low on an L40S. The default 181.0 is L40S dense bf16 with
fp32 accumulate, which is what torch's matmuls do; the datasheet's 362.05 is the
2:1-sparsity number and does not apply. Arm-to-arm RATIOS are peak-independent.
"""

import argparse
import os
import pathlib
import random
import re
import statistics
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
OUT = pathlib.Path("/data/151-2/users/tockier/profiling/vit_sweep")

SIZES = ("0_8b", "2b")
DATASETS = {
    "plotqa": "/data/151-1/datasets/plotqa_cot",
    "llavarecap": "/data/151-1/datasets/llava_recap",
}
ARMS = ("vlm", "novit", "novit_matched")
SEQ_LEN = 4096
TOTAL_STEPS = 30
WARMUP = 10
MIN_UTIL = 95.0
PEAK_TFLOPS = 181.0

TOML = """\
# Generated by scripts/vit_sweep.py -- edit the script, not this file.
[model]
model_name = "Qwen/Qwen3.5-{pretty}"
model_config = "{model_config}"
train_vit = true
train_llm = true
train_mlp = true

[wandb]
run_name = "{cell}"
project_name = "qwen3_5_local"
entity_name = "bsc_runs"
log_topk = false

[training]
model_dir = "/data/151-1/users/tockier/qwen_finetune/cache/qwen35_2b"
chat_template = "assets/chat_template_sft.jinja"
output_dir = "/data/151-2/users/tockier/qwen_finetune/checkpoints/vit_sweep_{cell}"
random_init = true
save_steps = 100000
total_steps = {total_steps}
warmup_steps = 5
scheduler_type = "cosine"
lr_llm = 1e-5
lr_mlp = 1e-5
lr_vit = 1e-6
tp_size = 1
data_parallel = "fsdp"
reshard_after_forward = "never"
compile = true
dynamo_recompile_limit = 64
tpi_multiplier = 1
adamw_impl = "foreach_sr"
master_dtype = "bfloat16"
grad_reduce_dtype = "float32"
deterministic = false
clear_cache_vram = 0

[data]
data_path = "{data_path}"
seq_len = {seq_len}
tokens_per_microbatch = 0
shuffle_buffer_size = 100
packing_buffer_size = 100
max_samples_per_sequence = 100
repeat = true
save_dataloader_state = false
"""

ANSI = re.compile(r"\x1b\[[0-9;]*m")
STEP = re.compile(
    r" - (\d+) - .*?tps (\d+) .*?tflops ([0-9.]+).*?time ([0-9.]+)s"
    r".*?mem ([0-9.]+)/([0-9.]+)G.*?data_pct ([0-9.]+)%"
    r".*?nsamples (\d+).*?batch_util ([0-9.]+)%"
)


def cell_name(size, data, arm):
    return f"{size}_{data}_{arm}"


def model_config(size, arm):
    stem = f"qwen3_5_{size}" if arm == "vlm" else f"qwen3_5_{size}_{arm}"
    return f"configs/models/{stem}.json"


def write_toml(size, data, arm):
    cfg_dir = OUT / "configs"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    path = cfg_dir / f"{cell_name(size, data, arm)}.toml"
    path.write_text(TOML.format(
        pretty=size.replace("_", ".").upper(),
        model_config=model_config(size, arm),
        cell=cell_name(size, data, arm),
        data_path=DATASETS[data],
        seq_len=SEQ_LEN,
        total_steps=TOTAL_STEPS,
    ))
    return path


def run_size(size, gpu):
    """Every cell of one size, sequentially, pinned to one GPU."""
    env = dict(os.environ,
               CUDA_DEVICE_ORDER="PCI_BUS_ID",
               CUDA_VISIBLE_DEVICES=str(gpu),
               WANDB_MODE="offline",
               HF_HUB_OFFLINE="1",
               OMP_NUM_THREADS="16",
               PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True")
    for data in DATASETS:
        for arm in ARMS:
            cell = cell_name(size, data, arm)
            log = OUT / f"{cell}.log"
            toml = write_toml(size, data, arm)
            print(f"=== {cell} (gpu {gpu}) -> {log}", flush=True)
            with log.open("wb") as fh:
                rc = subprocess.call(
                    ["torchrun", "--nproc_per_node=1",
                     f"--master_port={random.randint(20000, 29999)}",
                     "-m", "train.train_qwen", "--config", str(toml)],
                    cwd=REPO, env=env, stdout=fh, stderr=subprocess.STDOUT)
            if rc:
                print(f"    {cell} exited {rc}", flush=True)


def read(size, data, arm, peak):
    log = OUT / f"{cell_name(size, data, arm)}.log"
    if not log.exists():
        return None
    text = ANSI.sub("", log.read_text(errors="replace"))
    rows = [
        dict(tps=int(tps), tflops=float(tf), time=float(t), mem=float(m),
             data_pct=float(d), nsamples=int(ns), util=float(u))
        for _s, tps, tf, t, m, _r, d, ns, u in STEP.findall(text)
    ]
    oom = "OutOfMemory" in text or "out of memory" in text
    good = [r for r in rows[WARMUP:] if r["util"] >= MIN_UTIL]
    if not good:
        return dict(n=0, steps=len(rows), oom=oom)
    med = {k: statistics.median(r[k] for r in good)
           for k in ("tps", "tflops", "time", "mem", "data_pct", "nsamples", "util")}
    med.update(n=len(good), steps=len(rows), oom=oom,
               tflop_per_step=med["tflops"] * med["time"],
               mfu=med["tflops"] / peak * 100)
    return med


def report(peak):
    print(f"\npeak {peak:.1f} TFLOP/s assumed for MFU; seq_len {SEQ_LEN}; "
          f"medians over steps past {WARMUP} at >={MIN_UTIL:.0f}% fill\n")
    head = (f"{'cell':30s} {'n':>5s} {'MFU':>6s} {'TFLOP/s':>8s} {'tps':>8s} "
            f"{'step':>8s} {'TFLOP/st':>9s} {'mem':>7s} {'smp':>4s} {'data':>6s}")
    print(head)
    print("-" * len(head))
    got = {}
    for size in SIZES:
        for data in DATASETS:
            for arm in ARMS:
                name = cell_name(size, data, arm)
                m = read(size, data, arm, peak)
                if m is None:
                    print(f"{name:30s} {'-':>5s}  no log")
                    continue
                if not m["n"]:
                    why = "OOM" if m["oom"] else f"{m['steps']} steps, none usable"
                    print(f"{name:30s} {'-':>5s}  {why}")
                    continue
                got[(size, data, arm)] = m
                print(f"{name:30s} {m['n']:2d}/{m['steps']:<2d} "
                      f"{m['mfu']:5.1f}% {m['tflops']:8.1f} {m['tps']:8.0f} "
                      f"{m['time']:7.3f}s {m['tflop_per_step']:9.2f} "
                      f"{m['mem']:6.1f}G {m['nsamples']:4.0f} {m['data_pct']:5.2f}%")

    for size in SIZES:
        for data in DATASETS:
            base = got.get((size, data, "vlm"))
            nov = got.get((size, data, "novit"))
            if not base:
                continue
            print(f"\n--- {size} on {data}: real model {base['mfu']:.1f}% MFU, "
                  f"{base['tps']:.0f} tps")
            if nov:
                share = 1 - nov["tflop_per_step"] / base["tflop_per_step"]
                print(f"    ViT is {share * 100:.1f}% of modeled FLOPs per step "
                      f"-- that is this data's image density, measured")
            for arm in ("novit", "novit_matched"):
                m = got.get((size, data, arm))
                if not m:
                    print(f"    {arm:14s} missing")
                    continue
                note = "smaller model" if arm == "novit" else "same parameter count"
                print(f"    {arm:14s} MFU {base['mfu']:5.1f}% -> {m['mfu']:5.1f}%   "
                      f"tps {m['tps'] / base['tps']:.3f}x "
                      f"({(m['tps'] / base['tps'] - 1) * 100:+5.1f}%)   "
                      f"[{note}]")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--gpus", default="4,6",
                    help="one GPU per model size, run in parallel. Every arm of a "
                         "cell stays on ONE card -- splitting a comparison across "
                         "cards measures the cards.")
    ap.add_argument("--peak-tflops", type=float, default=PEAK_TFLOPS)
    args = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    if not args.report_only:
        gpus = [g.strip() for g in args.gpus.split(",") if g.strip()]
        procs = []
        for i, size in enumerate(SIZES):
            gpu = gpus[i % len(gpus)]
            procs.append(subprocess.Popen(
                [sys.executable, __file__, "--_run-size", size, "--_gpu", gpu],
                cwd=REPO))
        for p in procs:
            p.wait()
    report(args.peak_tflops)


if __name__ == "__main__":
    # the worker form: one size on one GPU, invoked by main()
    if "--_run-size" in sys.argv:
        size = sys.argv[sys.argv.index("--_run-size") + 1]
        gpu = sys.argv[sys.argv.index("--_gpu") + 1]
        run_size(size, gpu)
        sys.exit(0)
    sys.exit(main())
